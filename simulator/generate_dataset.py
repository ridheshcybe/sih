#!/usr/bin/env python3
"""Generate the labeled ML training dataset (train/val/test split by mission).

Usage:
  python -m simulator.generate_dataset --missions 40 --rows-per-mission 900
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

from simulator.fault_injection import FAULT_TYPES
from simulator.mission_profiles import PROFILE_NAMES
from simulator.simulate import simulate_mission

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"


def _mission_plan(n_missions: int) -> list:
    """Deterministic mission plan balancing healthy vs each fault type.

    Round-robin over fault types for the faulty share so every fault type gets
    (roughly) the same number of missions; profiles rotate independently.
    """
    n_healthy = n_missions * 2 // 5          # ~40% healthy
    n_faulty = n_missions - n_healthy
    plan = [None] * n_healthy
    for j in range(n_faulty):
        plan.append(FAULT_TYPES[j % len(FAULT_TYPES)])
    return plan


def build_dataset(n_missions: int, rows_per_mission: int, seed: int = 7) -> pd.DataFrame:
    """Generate a mix of healthy and faulty missions across all profiles."""
    plan = _mission_plan(n_missions)
    frames = []
    for i in range(n_missions):
        profile = PROFILE_NAMES[i % len(PROFILE_NAMES)]
        base_seed = seed * 1000 + i
        fault_type = plan[i]
        if fault_type is None:
            severity = 0.0
        else:
            severity = 0.4 + 0.5 * ((i * 7) % 10) / 10.0
        duration = rows_per_mission * 0.1  # ~90 s per 900 rows
        fault_start = duration * 0.35
        fault_duration = duration * 0.4
        df = simulate_mission(
            profile_id=profile,
            duration_s=duration,
            fault_type=fault_type,
            severity=severity,
            fault_start_s=fault_start,
            fault_duration_s=fault_duration,
            seed=base_seed,
        )
        frames.append(df)
        print(f"  mission {i + 1}/{n_missions}: profile={profile} fault={fault_type} "
              f"severity={severity:.2f} rows={len(df)}")
    return pd.concat(frames, ignore_index=True)


def _mission_fault(df: pd.DataFrame, mission_id: str) -> str:
    """Dominant non-healthy fault label for a mission ('none' if healthy)."""
    labels = df.loc[df["mission_id"] == mission_id, "fault_label"]
    faulty = labels[labels != "none"]
    if faulty.empty:
        return "none"
    return str(faulty.value_counts().idxmax())


def split_by_mission(df: pd.DataFrame, train_frac=0.7, val_frac=0.15, seed: int = 1) -> tuple:
    """Split by mission id, stratified by dominant fault type (no leakage).

    Random splits can leave entire fault classes out of val/test, which makes
    per-fault F1 impossible to evaluate. Stratifying keeps every fault type
    represented in every split whenever there are enough missions of it.
    """
    missions = list(df["mission_id"].unique())
    rng = np.random.default_rng(seed)
    rng.shuffle(missions)

    by_fault: dict = {}
    for m in missions:
        by_fault.setdefault(_mission_fault(df, m), []).append(m)

    train_ids: list = []
    val_ids: list = []
    test_ids: list = []
    for fault, ms in sorted(by_fault.items()):
        n = len(ms)
        if n == 1:
            train_ids += ms
            continue
        n_train = int(round(n * train_frac))
        n_val = int(round(n * val_frac))
        if n >= 3:
            # keep at least one mission per fault type in val and in test
            n_val = max(n_val, 1)
            n_test = max(n - n_train - n_val, 1)
            n_train = n - n_val - n_test
        else:  # n == 2: one to train, one to val
            n_train, n_val, n_test = 1, 1, 0
        train_ids += ms[:n_train]
        val_ids += ms[n_train:n_train + n_val]
        test_ids += ms[n_train + n_val:]
    return (
        df[df["mission_id"].isin(train_ids)],
        df[df["mission_id"].isin(val_ids)],
        df[df["mission_id"].isin(test_ids)],
    )


def write_dataset_csvs(train: pd.DataFrame, val: pd.DataFrame, test: pd.DataFrame) -> None:
    DATA_DIR.mkdir(exist_ok=True)
    for name, part in (("train", train), ("val", val), ("test", test)):
        path = DATA_DIR / f"{name}.csv"
        part.to_csv(path, index=False)
        print(f"  wrote {path} ({len(part)} rows)")
    readme = DATA_DIR / "README.md"
    readme.write_text(
        f"""# SIH26054 Synthetic Telemetry Dataset

Generated by `python -m simulator.generate_dataset`.

- Rows: train={len(train)}, val={len(val)}, test={len(test)}
- Profiles: {', '.join(PROFILE_NAMES)}
- Faults: {', '.join(FAULT_TYPES)} (plus healthy missions)

## Columns
- timestamp: ISO-8601 UTC
- mission_id: unique per mission (splits are per mission, no leakage)
- profile_id / phase / throttle
- Sensors: rpm, cht, egt, oil_pressure, oil_temperature, fuel_flow,
  vibration_rms, battery_voltage, alternator_current, injection_timing,
  altitude, ambient_temperature
- Labels:
  - fault_label: dominant fault type or 'none'
  - fault_severity: 0..1 magnitude of the injected fault
  - degradation_level: 0..1 engine degradation at that moment
  - rul_label: Remaining Useful Life in hours consistent with degradation

> Synthetic data only. Not validated against real engines; not flight-certified.
""",
        encoding="utf-8",
    )
    print(f"  wrote {readme}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate labeled synthetic dataset for ML training")
    parser.add_argument("--missions", type=int, default=40, help="number of missions to generate")
    parser.add_argument("--rows-per-mission", type=int, default=4000, help="telemetry rows per mission (~10 Hz); 4000 = 400 s so thermal lags settle")
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()

    print("Generating missions ...")
    df = build_dataset(args.missions, args.rows_per_mission, args.seed)
    train, val, test = split_by_mission(df)
    print("Writing CSVs ...")
    write_dataset_csvs(train, val, test)
    print("Done.")


if __name__ == "__main__":
    sys.exit(main())